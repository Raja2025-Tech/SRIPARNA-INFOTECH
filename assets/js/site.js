/* =========================================================
   SRIPARNA INFOTECH — SHARED UI BEHAVIOUR (v3.2)
   =========================================================
   Loaded by every page. Each block is guarded so a page that
   does not contain a given component simply skips it -- the
   homepage-only lead form must not throw on the service or
   legal pages.
========================================================= */
(function () {
    'use strict';

    const BUSINESS = {
        phone: '917003872122',
        tz: 'Asia/Kolkata',
        opens: 8,   // 08:00 IST, all 7 days
        closes: 22  // 22:00 IST
    };
    const track = (label, category) => {
        try { window.gtag && gtag('event', 'generate_lead', { event_category: category || 'Contact', event_label: label, value: 1 }); } catch (e) {}
    };

    /* ── Mobile nav ──
       Bar-to-X morph is pure CSS driven by .open on the button.
       Closes on link click, Escape, and taps outside the menu. */
    const ham  = document.getElementById('hamburger');
    const menu = document.getElementById('navMenu');
    if (ham && menu) {
        const setOpen = open => {
            menu.classList.toggle('open', open);
            ham.classList.toggle('open', open);
            ham.setAttribute('aria-expanded', String(open));
        };
        ham.addEventListener('click', () => setOpen(!menu.classList.contains('open')));
        menu.querySelectorAll('a').forEach(a => a.addEventListener('click', () => setOpen(false)));
        document.addEventListener('keydown', e => {
            if (e.key === 'Escape' && menu.classList.contains('open')) { setOpen(false); ham.focus(); }
        });
        document.addEventListener('click', e => {
            if (menu.classList.contains('open') && !menu.contains(e.target) && !ham.contains(e.target)) setOpen(false);
        });
    }

    /* ── Google reviews badge text ──
       reviews-config.js is generated by Jekyll from _data/reviews.yml, the
       same file the HTML and JSON-LD are rendered from, so this can never
       disagree with the page source again (it used to overwrite 24 with 19). */
    if (window.SI_REVIEWS) {
        const { rating, count, url } = window.SI_REVIEWS;
        document.querySelectorAll('[data-review="rating"]').forEach(el => { el.textContent = Number(rating).toFixed(1); });
        document.querySelectorAll('[data-review="count"]').forEach(el => { el.textContent = count; });
        document.querySelectorAll('[data-review="stars"]').forEach(el => { el.textContent = '★★★★★'.slice(0, Math.round(rating)); });
        document.querySelectorAll('[data-review="url"]').forEach(el => { if (el.tagName === 'A') el.href = url; });
    }

    /* ── Live "Open now / Closed" status (IST, regardless of visitor's TZ) ── */
    const statusEls = document.querySelectorAll('[data-open-status]');
    if (statusEls.length) {
        const fmt = h => (h % 12 || 12) + (h < 12 ? ' AM' : ' PM');
        const update = () => {
            let h, m;
            try {
                const parts = new Intl.DateTimeFormat('en-GB', { timeZone: BUSINESS.tz, hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).formatToParts(new Date());
                h = +parts.find(p => p.type === 'hour').value;
                m = +parts.find(p => p.type === 'minute').value;
            } catch (e) { return; }
            const mins = h * 60 + m, open = BUSINESS.opens * 60, close = BUSINESS.closes * 60;
            const isOpen = mins >= open && mins < close;
            let text;
            if (isOpen) {
                const left = close - mins;
                text = left <= 60 ? `Open now · closes in ${left} min` : `Open now · until ${fmt(BUSINESS.closes)}`;
            } else {
                text = `Closed now · opens ${mins < open ? 'today' : 'tomorrow'} at ${fmt(BUSINESS.opens)}`;
            }
            statusEls.forEach(el => { el.textContent = text; el.classList.toggle('closed', !isOpen); });
        };
        update();
        setInterval(update, 60 * 1000);
    }

    /* ── Sticky nav style (rAF-throttled) ── */
    const nav = document.getElementById('nav');
    if (nav) {
        let ticking = false;
        const onScroll = () => {
            if (ticking) return;
            ticking = true;
            requestAnimationFrame(() => { nav.classList.toggle('scrolled', window.scrollY > 24); ticking = false; });
        };
        window.addEventListener('scroll', onScroll, { passive: true });
        onScroll();
    }

    /* ── Floating WhatsApp: hidden while the homepage hero is visible ── */
    const fab = document.querySelector('.floating-wa');
    const hero = document.getElementById('hero');
    if (fab && hero && 'IntersectionObserver' in window) {
        new IntersectionObserver(([e]) => fab.classList.toggle('fab-hidden', e.isIntersecting), { threshold: 0.15 }).observe(hero);
    }

    /* ── Scroll reveal ──
       Falls back to showing everything when IntersectionObserver is
       unavailable, so content can never be stuck at opacity:0. */
    const reveals = document.querySelectorAll('.reveal, .reveal-scale, .reveal-left, .reveal-right');
    if ('IntersectionObserver' in window) {
        const revealObs = new IntersectionObserver(
            entries => entries.forEach(e => {
                if (e.isIntersecting) { e.target.classList.add('in'); revealObs.unobserve(e.target); }
            }),
            { threshold: 0.1, rootMargin: '0px 0px -44px 0px' }
        );
        reveals.forEach(el => revealObs.observe(el));
    } else {
        reveals.forEach(el => el.classList.add('in'));
    }

    /* ── FAQ ──
       Every FAQ is now a native <details>, which is keyboard-accessible on
       its own. The old JS accordion also bound to <summary class="faq-q">
       and its Enter/Space preventDefault() blocked keyboard users from
       opening any FAQ on the service pages. This only keeps one item open
       at a time and records which question was opened. */
    document.querySelectorAll('details.faq-item').forEach(d => {
        d.addEventListener('toggle', () => {
            if (!d.open) return;
            d.parentElement.querySelectorAll('details.faq-item[open]').forEach(o => { if (o !== d) o.open = false; });
            try { window.gtag && gtag('event', 'faq_open', { event_label: d.querySelector('summary')?.textContent.trim().slice(0, 100) }); } catch (e) {}
        });
    });

    /* ── Lead form (homepage) ── */
    const leadForm = document.getElementById('leadForm');
    if (leadForm) {
        const ENDPOINT = 'https://sriparna-infotech-lead-form.thetechachiever.workers.dev';
        const $ = id => document.getElementById(id);
        const btn = $('fSubmit'), errD = $('fErr'), waAlt = $('fWhatsApp');
        const fields = {
            name:    { el: $('f-name'),    hint: $('h-name') },
            phone:   { el: $('f-phone'),   hint: $('h-phone') },
            service: { el: $('f-service'), hint: $('h-service') },
            message: { el: $('f-msg'),     hint: $('h-msg') }
        };
        const startedAt = Date.now();

        // Accepts 98xxxxxxxx, 098..., +91 98..., 91-98... ; returns 10 digits or null.
        const normalisePhone = v => {
            let d = (v || '').replace(/\D/g, '');
            if (d.length === 12 && d.startsWith('91')) d = d.slice(2);
            if (d.length === 11 && d.startsWith('0')) d = d.slice(1);
            return /^[6-9]\d{9}$/.test(d) ? d : null;
        };
        const rules = {
            name:    v => v.trim().length >= 2 || 'Please enter your name.',
            phone:   v => !!normalisePhone(v) || 'Enter a valid 10-digit Indian mobile number.',
            service: v => !!v || 'Please choose a service.',
            message: v => v.trim().length >= 5 || 'Tell us a little about the problem.'
        };
        const check = key => {
            const f = fields[key], res = rules[key](f.el.value);
            const ok = res === true;
            f.el.setAttribute('aria-invalid', ok ? 'false' : 'true');
            f.hint.textContent = ok ? '' : res;
            return ok;
        };
        Object.keys(fields).forEach(k => {
            const el = fields[k].el;
            el.addEventListener('blur', () => { if (el.value) check(k); });
            el.addEventListener('input', () => { if (el.getAttribute('aria-invalid') === 'true') check(k); });
            el.addEventListener('change', () => { if (el.getAttribute('aria-invalid') === 'true') check(k); });
        });

        const waText = p => `Hello Sriparna Infotech,\nName: ${p.name}\nPhone: ${p.phone}\nService: ${p.service}\n\n${p.message}`;

        leadForm.addEventListener('submit', async e => {
            e.preventDefault();
            errD.style.display = 'none';
            waAlt.classList.remove('show');

            const invalid = Object.keys(fields).filter(k => !check(k));
            if (invalid.length) { fields[invalid[0]].el.focus(); return; }

            const payload = {
                name:    fields.name.el.value.trim(),
                phone:   '+91' + normalisePhone(fields.phone.el.value),
                service: fields.service.el.value,
                message: fields.message.el.value.trim()
            };
            waAlt.href = `https://wa.me/${BUSINESS.phone}?text=${encodeURIComponent(waText(payload))}`;

            // Bots: honeypot filled, or submitted faster than a human could type.
            if ($('f-website').value || Date.now() - startedAt < 2500) {
                window.location.href = '/thank-you';
                return;
            }

            const orig = btn.textContent;
            btn.textContent = 'Sending…';
            btn.disabled = true;
            const ctrl = new AbortController();
            const timer = setTimeout(() => ctrl.abort(), 12000);
            try {
                const res = await fetch(ENDPOINT, {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify(payload),
                    signal: ctrl.signal
                });
                let result = {};
                try { result = await res.json(); } catch (_) { /* non-JSON error page */ }
                if (!res.ok || !result.success) throw new Error(result.error || `HTTP ${res.status}`);
                try { sessionStorage.setItem('si_lead_sent', '1'); } catch (_) {}
                leadForm.reset();
                window.location.href = '/thank-you';
            } catch (err) {
                errD.textContent = 'We couldn’t send your message just now. Tap the WhatsApp button below to send the same details instantly, or call +91 70038 72122.';
                errD.style.display = 'block';
                waAlt.classList.add('show');
                try { window.gtag && gtag('event', 'form_error', { event_label: String(err && err.message || err).slice(0, 100) }); } catch (_) {}
            } finally {
                clearTimeout(timer);
                btn.textContent = orig;
                btn.disabled = false;
            }
        });
        waAlt.addEventListener('click', () => track('Form WhatsApp Fallback', 'Form'));
    }

    /* ── Offline support: register the service worker (see /sw.js) ── */
    if ('serviceWorker' in navigator && location.protocol === 'https:') {
        window.addEventListener('load', () => { navigator.serviceWorker.register('/sw.js').catch(() => {}); });
    }

})();
